import fs from 'node:fs';
import crypto from 'node:crypto';
const b = JSON.parse(fs.readFileSync('web/draw/motion-assets/bundle.json', 'utf8'));
console.log('motion-assets bundle keys:', Object.keys(b));
console.log('mesh verts:', b.mesh.vertices.length, 'faces:', b.mesh.faces.length / 3, 'colors:', Array.isArray(b.mesh.colors));
console.log('rig joints:', b.rig.joints.map(j => j.id).join(','));
console.log('rig has vertexWeights:', 'vertexWeights' in b.rig);
console.log('clips:', (b.clips || []).map(c => c.id).join(','));
const mrig = JSON.parse(fs.readFileSync('web/draw/mocap-assets/rig.json', 'utf8'));
console.log('joint sets equal:', JSON.stringify(b.rig.joints) === JSON.stringify(mrig.joints));
const r1 = JSON.parse(fs.readFileSync('delivery/body-blockout-r1/mesh.json', 'utf8'));
const same = JSON.stringify(b.mesh.vertices) === JSON.stringify(r1.vertices) && JSON.stringify(b.mesh.faces) === JSON.stringify(r1.faces);
console.log('mesh identical to body-blockout-r1:', same);
const sha = p => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
console.log('r1 mesh sha256:', sha('delivery/body-blockout-r1/mesh.json'));
console.log('r1 controls sha256:', sha('delivery/body-blockout-r1/controls.json'));
console.log('vertexJoint equal:', JSON.stringify(b.rig.vertexJoint) === JSON.stringify(mrig.vertexJoint));
