/* 02-demo：loft 原语三用例（直管=圆柱、弯曲变径=角状、竖弯=裙袖） */
(function () { 'use strict';
  window.gms.clear();
  window.__gmsBatch = true;
  // A 直管
  loft([[-0.16, 0.06, 0], [0, 0.075, 0], [0.16, 0.06, 0]], [0.020, 0.020, 0.020], 10, 12, function () { return '#f7f9fc'; }, 0.0015);
  // B 弯曲变径（角/鞋通用形状）
  loft([[0, 0.02, 0], [0, 0.10, -0.05], [0, 0.17, -0.13]], [0.022, 0.016, 0.005], 12, 12, function (i, j) { return j % 2 ? '#7a3140' : '#20242c'; }, 0.0015);
  // C 竖弯（马尾/飘带领口）
  loft([[0.0, 0.02, 0.14], [0.01, 0.12, 0.16], [-0.01, 0.22, 0.15]], [0.012, 0.018, 0.010], 10, 12, function () { return '#a9d4f5'; }, 0.0015);
  window.__gmsBatchEnd && window.__gmsBatchEnd();
})();
