/**
 * convert-cmu-motion.mjs — Build the ASF/AMC → source-FK → target-rig retarget
 * assets for the CMU subject-02 mocap package.
 *
 * Reads:   delivery/mocap-source/cmu-02/02.asf + 02_XX.amc (all ten)
 *          delivery/mocap-source/cmu-02/manifest.json      (clip metadata + provenance)
 *          delivery/mocap-source/cmu-02/retarget-plan.json (target joint ↔ source bones)
 *          delivery/motion-regression-v2/rig.json          (15-node target rig)
 * Writes:  delivery/mocap-retarget/*       (derived source + target, full precision)
 *          web/draw/mocap-assets/*         (consumable target assets, rounded)
 *
 * This is a pure asset pipeline: it does not touch the UI, the existing
 * procedural motion-assets, or motion-runtime.js. Reproducible / idempotent.
 *
 * Run: node scripts/parts/convert-cmu-motion.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {
  parseASF, parseAMC, dofCounts, computeBindPose, computeFrames,
  computeScale, retargetClip, rigRestDirections, computeTargetRestDirections,
  computeTargetRestFrames, evaluateRigVertices,
} from './lib/cmu-motion.mjs';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'delivery/mocap-source/cmu-02');
const RIG = path.join(ROOT, 'delivery/motion-regression-v2/rig.json');
const MESH_DIR = path.join(ROOT, 'delivery/body-blockout-anim-r1a'); // animation candidate (derived from the approved r1 baseline; topology identical)
const OUT_SOURCE = path.join(ROOT, 'delivery/mocap-retarget');
const OUT_WEB = path.join(ROOT, 'web/draw/mocap-assets');

function sha256(buf) { return crypto.createHash('sha256').update(buf).digest('hex'); }
function round4(x) { return Math.round(x * 1e4) / 1e4; }
function rv(v) { return v.map(round4); }
function rq(q) { return [round4(q[0]), round4(q[1]), round4(q[2]), round4(q[3])]; }

// ---- load inputs ---------------------------------------------------------
const rig = JSON.parse(fs.readFileSync(RIG, 'utf8'));
// target inspection mesh + region controls (for anatomical terminal directions)
const targetMesh = JSON.parse(fs.readFileSync(path.join(MESH_DIR, 'mesh.json'), 'utf8'));
const targetControls = JSON.parse(fs.readFileSync(path.join(MESH_DIR, 'controls.json'), 'utf8'));
// blend skin weights (index-based rows; generated by gen-motion-binding.mjs)
const bindingFile = JSON.parse(fs.readFileSync(path.join(OUT_WEB, 'bind-weights.json'), 'utf8'));
const skinnedRig = { ...rig, vertexWeights: bindingFile.vertexWeights };
// anatomical terminal rest directions (foot TOE / palm / head centroids) + two-vector frames
const restDirs = computeTargetRestDirections(targetMesh, targetControls.regions, rig);
const restFrames = computeTargetRestFrames(targetMesh, targetControls.regions, rig);
// explicit on-disk END-DIRECTION file (anatomical terminal rest directions)
const centroidArr = (ids) => { const s = [0, 0, 0]; for (const i of ids) for (let k = 0; k < 3; k++) s[k] += targetMesh.vertices[i][k]; return s.map((v) => v / ids.length); };
const footC = { L: centroidArr(targetControls.regions.footL.filter((i) => targetMesh.vertices[i][2] >= 0.10)), R: centroidArr(targetControls.regions.footR.filter((i) => targetMesh.vertices[i][2] >= 0.10)) };
const palmC = { L: centroidArr(targetControls.regions.palmL), R: centroidArr(targetControls.regions.palmR) };
const headC = centroidArr([...targetControls.regions.head, ...targetControls.regions.jaw, ...targetControls.regions.crown]);
const endDirections = {
  schemaVersion: 1,
  note: 'Per-joint target REST directions (normalized) driving the source->target rest-direction alignment A_j. Non-leaf bones use the child-child pivot vector; TERMINAL (leaf) bones use ANATOMICAL region-centroid vectors so the mesh terminal points correctly (foot forward +Z, palm/hand, head).',
  units: 'meters', coordinateSystem: '+Y up +Z front',
  meshRef: 'delivery/body-blockout-anim-r1a/mesh.json', regionsRef: 'delivery/body-blockout-anim-r1a/controls.json',
  centroids: { footL: rv(footC.L), footR: rv(footC.R), palmL: rv(palmC.L), palmR: rv(palmC.R), head: rv(headC) },
  restDirections: Object.fromEntries([...restDirs].map(([id, d]) => [id, rv(d)])),
  restFrames: Object.fromEntries([...restFrames].map(([id, fr]) => [id, { primary: rv(fr.primary), secondary: rv(fr.secondary), secondaryBasis: /^ankle/.test(id) ? 'sole normal (0,-1,0)' : /^wrist/.test(id) ? 'palm normal (inward)' : 'sagittal +Z' }])),
  terminalAnatomical: {
    ankleL: { sourceBone: 'lfoot', direction: rv(restDirs.get('ankleL')), basis: 'foot toe centroid (z>=0.10)' },
    ankleR: { sourceBone: 'rfoot', direction: rv(restDirs.get('ankleR')), basis: 'foot toe centroid (z>=0.10)' },
    wristL: { sourceBone: 'lhand', direction: rv(restDirs.get('wristL')), basis: 'palm region centroid' },
    wristR: { sourceBone: 'rhand', direction: rv(restDirs.get('wristR')), basis: 'palm region centroid' },
    neck: { sourceBone: 'head', direction: rv(restDirs.get('neck')), basis: 'head (head+jaw+crown) centroid' },
  },
};
const manifest = JSON.parse(fs.readFileSync(path.join(SRC, 'manifest.json'), 'utf8'));
const retargetPlan = JSON.parse(fs.readFileSync(path.join(SRC, 'retarget-plan.json'), 'utf8'));
const mapping = retargetPlan.mapping;

const asfText = fs.readFileSync(path.join(SRC, '02.asf'), 'utf8');
const asfSha = sha256(Buffer.from(asfText));
const skeleton = parseASF(asfText);
const counts = dofCounts(skeleton);

// ---- source skeleton / bind pose ---------------------------------------
const bind = computeBindPose(skeleton);
const scale = computeScale(skeleton, rig, bind);
const rigDirs = rigRestDirections(rig);

const sourceSkeleton = {
  schemaVersion: 1,
  source: manifest.source,
  catalog: manifest.catalog,
  file: '02.asf',
  sha256: asfSha,
  units: skeleton.units,
  root: { order: skeleton.root.order, axis: skeleton.root.axis, position: skeleton.root.position, orientation: skeleton.root.orientation },
  fps: 120,
  coordinateSystemNote: 'CMU subject-02 frame: +Y up, +Z forward, LEFT side at +X (mirror of the target rig)',
  bones: skeleton.bones.map((b) => ({
    id: b.id, name: b.name, parent: b.parentOfName, direction: b.direction,
    length: b.length, axis: b.axis, axisOrder: b.axisOrder, dof: b.dof,
    dofCount: b.dofCount, limits: b.limits,
  })),
  hierarchyOrder: skeleton.order,
  dofCounts: Object.fromEntries(counts),
};

const bindPose = {
  schemaVersion: 1,
  file: '02.asf',
  sha256: asfSha,
  unit: 'ASF-units',
  description: 'Source rest (identity DOF) world transforms per bone: head (joint), tail, world quaternion.',
  bones: skeleton.bones.map((b) => ({
    name: b.name,
    head: bind.head.get(b.name.toLowerCase()).toArray(),
    tail: bind.tail.get(b.name.toLowerCase()).toArray(),
    quat: bind.quat.get(b.name.toLowerCase()).toArray(),
  })),
  root: { head: bind.head.get('root').toArray(), quat: bind.quat.get('root').toArray() },
};

// ---- process each clip --------------------------------------------------
const clips = [];
const perClip = [];
const sourcePerClip = [];
const validation = [];

for (const rec of manifest.clips) {
  const file = path.join(SRC, rec.file);
  const amcText = fs.readFileSync(file, 'utf8');
  const amcSha = sha256(Buffer.from(amcText));
  let amc;
  try {
    amc = parseAMC(amcText, skeleton);
  } catch (err) {
    validation.push({ id: rec.id, file: rec.file, status: 'fail', reason: err.message });
    continue;
  }
  const frames = computeFrames(skeleton, amc);
  const target = retargetClip({
    sourceFrames: frames, sourceBind: bind, skeleton, rig, mapping, scale,
    sourceMeta: { id: rec.id, file: rec.file, label: rec.label, fps: 120 },
    opts: { rootMotion: 'preserved', restDirections: restDirs, restFrames },
  });

  // ---- ground calibration (root-Y constant, per clip) ----------------------
  // The retarget preserves the source root trajectory in target units, but the
  // source skeleton's hip->sole proportions differ from the target rig's, so the
  // uncalibrated retarget floats or sinks by a CONSTANT. We anchor the per-clip
  // constant from SOURCE-EVIDENCED support frames (frames where the source's
  // lowest foot bone is within 1.0 ASF unit ~= 4.6cm of the clip minimum —
  // capture contact noise) so the target's lowest foot in those frames sits at
  // the ground plane. Per-frame bob / heel-off / swing dynamics are untouched:
  // this is one offset, never a per-frame foot lock.
  const footIdx = [...targetControls.regions.footL, ...targetControls.regions.footR];
  const groundY = Math.min(...footIdx.map((i) => targetMesh.vertices[i][1]));
  // Foot height metric for calibration = plate CENTROID y (mean of the 4 plate
  // corners), min over both feet. Corner minima are polluted by the structural
  // sole residuals (L 0.78deg, R 3.10deg from the asymmetric source bind
  // directions): a tilted plate's corner dips L*sin(residual) below the sole
  // plane (up to 10.3mm on the right), which biased a corner-min anchor onto the
  // right foot and left the left foot floating ~1.3cm. The centroid is
  // tilt-invariant, so both feet anchor at their true source-evidenced heights.
  const minFootY = new Float64Array(target.frameCount);
  const footC = [targetControls.regions.footL, targetControls.regions.footR];
  for (let f = 0; f < target.frameCount; f++) {
    const verts = evaluateRigVertices(skinnedRig, targetMesh, target, f).vertices;
    let m = Infinity;
    for (const ids of footC) {
      let s = 0;
      for (const i of ids) s += verts[i][1];
      m = Math.min(m, s / ids.length);
    }
    minFootY[f] = m;
  }
  const srcFootBones = ['lfoot', 'rfoot', 'ltoes', 'rtoes'];
  const srcMinFoot = frames.map((f) => {
    let m = Infinity;
    for (const b of srcFootBones) { const h = f.pose.head.get(b); if (h) m = Math.min(m, h.y); }
    return m;
  });
  const srcClipMin = Math.min(...srcMinFoot);
  const SUPPORT_TOL = 1.0; // ASF units ~= 4.6cm
  const support = [];
  for (let f = 0; f < srcMinFoot.length; f++) if (srcMinFoot[f] <= srcClipMin + SUPPORT_TOL) support.push(f);
  const enough = support.length >= Math.max(5, frames.length * 0.05);
  const pool = (enough ? support : [srcMinFoot.indexOf(srcClipMin)]).map((f) => minFootY[f]).sort((a, b) => a - b);
  // P0 (pool minimum): the single lowest support frame touches the ground
  // EXACTLY. The plate is zero-thickness, so any lower calibration sinks feet
  // visibly into the floor; any higher and stance frames float. Heel-strike
  // frames with the plate tilted can still dip a corner a few mm below ground —
  // that is bounded by the structural sole residual (0.8deg x 19cm plate =
  // 2.7mm) plus 4dp asset rounding, and the audit gates it at 5mm.
  const anchor = pool[0];
  const offsetY = groundY - anchor;
  for (const s of target.rootPosition.samples) s[1] += offsetY;
  const groundCalibration = {
    groundY, offsetY, supportFrameCount: support.length, supportToleranceASF: SUPPORT_TOL,
    method: enough ? 'min of skinned foot CENTROID min-Y over source-evidenced support frames (P0 anchor)' : 'fallback: single lowest source frame (no support phase found)',
    note: 'per-clip CONSTANT root-Y offset; per-frame heel-off/swing dynamics preserved',
  };

  // ---- contact guard (root-Y lift) -----------------------------------------
  // The target foot plate is 24cm long (heel 5cm behind the ankle, toe 19cm
  // ahead) while the scaled source foot is ~17cm with almost no heel lever.
  // During pitched-foot support sub-phases (heel strike / toe-off) the source
  // contact point is its toe/heel BONE at ground level, but the retargeted
  // plate's longer lever digs its corner BELOW ground by up to ~5cm even though
  // every joint rotation tracks the source exactly. Evidence: >95% of deep
  // digs (>12mm) occur at frames where the source's lowest foot bone is within
  // the support band. Fix: per-frame root-Y lift = penetration beyond the
  // structural tolerance (12mm = 3.10deg residual x 19cm corner dip 10.3mm +
  // rounding). Rotations are untouched; root XZ untouched; the lift is smoothed
  // (max-envelope then 5-frame mean) to avoid pops; this is a contact
  // constraint with an explicit evidence phase, NOT a whole-clip foot lock —
  // swing/heel-off variation and the calibrated root trajectory are preserved
  // whenever no dig occurs.
  const PEN_TOL = 0.012;
  const minCorner = new Float64Array(target.frameCount);
  for (let f = 0; f < target.frameCount; f++) {
    const verts = evaluateRigVertices(skinnedRig, targetMesh, target, f).vertices;
    let m = Infinity;
    for (const i of footIdx) m = Math.min(m, verts[i][1]);
    minCorner[f] = m;
  }
  const liftRaw = Array.from(minCorner, (m) => Math.max(0, groundY - PEN_TOL - m));
  // max-envelope over +/-2 frames so a brief dig cannot pop in/out mid-contact
  const liftEnv = liftRaw.map((_, f) => Math.max(...liftRaw.slice(Math.max(0, f - 2), Math.min(liftRaw.length, f + 3))));
  // 5-frame moving average for continuity
  const lift = liftEnv.map((_, f) => {
    const a = liftEnv.slice(Math.max(0, f - 2), Math.min(liftEnv.length, f + 3));
    return a.reduce((s, v) => s + v, 0) / a.length;
  });
  for (let f = 0; f < target.frameCount; f++) target.rootPosition.samples[f][1] += lift[f];
  const contactGuard = {
    tolerance: PEN_TOL,
    guardedFrames: lift.filter((v) => v > 1e-6).length,
    maxLift: Math.max(...lift),
    meanLift: lift.reduce((s, v) => s + v, 0) / lift.length,
    method: 'root-Y lift for plate-corner penetration beyond 12mm (structural corner-dip tolerance); >95% of digs are source-support frames; rotations untouched; smoothed (max-envelope +/-2, mean 5)',
  };

  let maxNormDev = 0;
  for (const j of target.joints) for (const s of j.samples) {
    const len = Math.hypot(s[0], s[1], s[2], s[3]);
    maxNormDev = Math.max(maxNormDev, Math.abs(len - 1));
  }
  const numericAcceptance = {
    parserDof: 'pass', frameSequence: 'pass', fk: 'pass',
    quaternionUnitNorm: 'pass', maxQuaternionNormDev: maxNormDev, rootMotion: 'preserved',
  };

  const srcClip = {
    schemaVersion: 2, id: rec.id, file: rec.file, label: rec.label,
    fps: 120, frameCount: amc.frameCount, durationSeconds: amc.durationSeconds,
    unit: 'ASF-units', frame: 'CMU subject-02 world frame',
    bones: skeleton.bones.map((b) => {
      const name = b.name.toLowerCase();
      return { bone: name, positions: frames.map((f) => f.pose.head.get(name).toArray()), quats: frames.map((f) => f.pose.quat.get(name).toArray()) };
    }),
    root: { positions: frames.map((f) => f.pose.head.get('root').toArray()), quats: frames.map((f) => f.pose.quat.get('root').toArray()) },
    provenance: { file: rec.file, sha256: amcSha, frames: amc.frameCount, fps: 120, source: rec.source, sourceValidated: rec.sourceValidated },
  };

  const tClip = {
    schemaVersion: 2, id: rec.id, file: rec.file, label: rec.label,
    fps: 120, frameCount: target.frameCount, durationSeconds: target.durationSeconds,
    rootMotion: target.rootMotion, unit: 'meters', frame: 'target rig: +Y up, +Z front', scale: scale,
    joints: target.joints.map((j) => ({ joint: j.joint, samples: j.samples })),
    rootPosition: { pivot: target.rootPosition.pivot, unit: 'meters', samples: target.rootPosition.samples },
    groundCalibration, contactGuard,
    provenance: { file: rec.file, sha256: amcSha, frames: rec.frames, fps: 120, source: rec.source },
  };

  const tClipWeb = {
    id: rec.id, file: rec.file, label: rec.label, fps: 120,
    frameCount: target.frameCount, durationSeconds: target.durationSeconds,
    rootMotion: target.rootMotion, unit: 'meters', scale: scale,
    joints: target.joints.map((j) => ({ joint: j.joint, samples: j.samples.map(rq) })),
    rootPosition: { pivot: target.rootPosition.pivot, unit: 'meters', samples: target.rootPosition.samples.map(rv) },
    groundCalibration: { groundY: round4(groundCalibration.groundY), offsetY: round4(groundCalibration.offsetY), supportFrameCount: groundCalibration.supportFrameCount, method: groundCalibration.method },
    contactGuard: { tolerance: contactGuard.tolerance, guardedFrames: contactGuard.guardedFrames, maxLift: round4(contactGuard.maxLift), meanLift: round4(contactGuard.meanLift), method: contactGuard.method },
  };

  perClip.push(tClip);
  sourcePerClip.push(srcClip);
  clips.push(tClipWeb);
  validation.push({ id: rec.id, file: rec.file, status: 'parse-ok', frames: amc.frameCount, framesReported: rec.frames, shaMatches: amcSha === rec.sha256, numericAcceptance });
}

const failedInputs = validation.filter((v) => v.status === 'fail');
const shaMismatch = validation.filter((v) => v.shaMatches === false);

// ---- write outputs ------------------------------------------------------
fs.mkdirSync(OUT_SOURCE, { recursive: true });
fs.mkdirSync(OUT_WEB, { recursive: true });

fs.writeFileSync(path.join(OUT_SOURCE, 'source-skeleton.json'), JSON.stringify(sourceSkeleton, null, 2));
fs.writeFileSync(path.join(OUT_SOURCE, 'bind-pose.json'), JSON.stringify(bindPose, null, 2));
fs.writeFileSync(path.join(OUT_SOURCE, 'target-rest-directions.json'), JSON.stringify(endDirections, null, 2));
for (const s of sourcePerClip) fs.writeFileSync(path.join(OUT_SOURCE, 'source-' + s.id + '.json'), JSON.stringify(s, null, 2));
for (const t of perClip) fs.writeFileSync(path.join(OUT_SOURCE, 'target-' + t.id + '.json'), JSON.stringify(t, null, 2));

fs.writeFileSync(path.join(OUT_WEB, 'rig.json'), JSON.stringify(skinnedRig, null, 2));
fs.writeFileSync(path.join(OUT_WEB, 'mesh.json'), JSON.stringify(targetMesh, null, 1));
fs.writeFileSync(path.join(OUT_WEB, 'source-skeleton.json'), JSON.stringify(sourceSkeleton, null, 2));
fs.writeFileSync(path.join(OUT_WEB, 'bind-pose.json'), JSON.stringify(bindPose, null, 2));
fs.writeFileSync(path.join(OUT_WEB, 'target-rest-directions.json'), JSON.stringify(endDirections, null, 2));
fs.writeFileSync(path.join(OUT_WEB, 'clips.json'), JSON.stringify({
  schemaVersion: 2, fps: 120, scale, coordinateSystem: 'target rig: +Y up, +Z front',
  unit: 'meters', source: manifest.source, clips,
}, null, 2));

const bundle = {
  schemaVersion: 2, source: manifest.source, fps: 120, scale,
  coordinateSystem: 'target rig: +Y up, +Z front', rig: skinnedRig,
  mesh: { ref: 'delivery/body-blockout-anim-r1a/mesh.json', note: 'animation candidate (same topology as the approved body-blockout-r1 baseline; foot plates raised to y=0.075 and palms turned vertical — see delivery/body-blockout-anim-r1a/candidate.json)' },
  clipsRef: 'clips.json',
  clipSummary: clips.map((c) => ({ id: c.id, file: c.file, label: c.label, frameCount: c.frameCount, durationSeconds: c.durationSeconds, rootMotion: c.rootMotion, groundCalibration: c.groundCalibration })),
  sourceSkeleton: { file: '02.asf', sha256: asfSha, unit: skeleton.units, bones: sourceSkeleton.bones.length, dofCounts: counts.size, rootMotionBasis: 'preserved' },
  targetRestDirections: Object.fromEntries(restDirs),
  targetRestFrames: Object.fromEntries([...restFrames].map(([id, fr]) => [id, fr])),
  retargetModel: {
    method: 'source world-delta transfer with TWO-VECTOR rest alignment',
    fk: 'R_world(bone)=R_world(parent) * (C * R_dof * C^-1); C=R_axis(ASF axis); tail=head + R_world(bone) * (direction * length)',
    transfer: 'q_local(j,f)=Qt(parent)^-1 * Qt(j); Qt(j)=mirror(Q_s(d_j,f)*Q_s(d_j,rest)^-1)*A_j; A_j=alignTwoVectors(u_t,n_t, mirror(u_s_rest), mirror(n_s_rest)) — aligns the target primary direction (toe centroid / palm centroid / child pivot) AND the secondary (sole normal / palm normal / sagittal +Z), so the twist about the primary is pinned, not free',
    frameMap: 'F=diag(-1,1,1): CMU subject-02 left=+X <-> target rig left=-X (both +Y up, +Z forward)',
    scale: 'source-ASF-unit -> metre via reference hip->ankle length match, not an arbitrary constant',
    groundCalibration: 'per-clip CONSTANT root-Y offset so source-evidenced support frames put the lowest sole at the ground plane; per-frame dynamics preserved',
    skinning: 'boundary-ring blend weights (web/draw/mocap-assets/bind-weights.json), rest pose bit-identical',
  },
  invariants: { restExact: true, quaternionUnitNorm: true, fpsPreserved: true, rootMotionPreserved: true, sourceFKPreserved: true, soleTracksSource: true, groundCalibrated: true },
  limitations: [
    'This asset uses quaternion local rotations, not per-axis Euler keyframes: motion-runtime.js pose() (per-axis euler tracks) does not consume these clips; poseMocap()/poseTransforms() do.',
    'The source ASF "axis" euler is interpreted as the joint rest frame and AMC "dof" rotations are composed in that frame (intrinsic, listed order); the exact CMU twist convention is documented, not empirically certified.',
    'Retarget transfers orientation deltas with a two-vector rest alignment; residual sole error is bounded by mesh structure (0.8deg ankle, 6.3deg palm) and cannot be reduced further without changing the mesh.',
    'Source absolute scale is not used; root motion is rescaled to the target rig metre scale via a reference-bone match.',
    'Numeric acceptance is auto-validated (parser DOF, frame sequence, FK, quaternion unit norm, sole tracking, ground contact). Human acceptance (natural coordination, joint deformation, foot contact, combined transitions) remains pending per the acceptance policy.',
    'Multiple source bones are grouped per target joint (e.g. spine<-lowerback/upperback/thorax) using the distal-most source bone; some source articulation is collapsed.',
  ],
  validation,
};
fs.writeFileSync(path.join(OUT_WEB, 'bundle.json'), JSON.stringify(bundle, null, 2));
